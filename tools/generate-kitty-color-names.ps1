param(
    [string] $Root = (Resolve-Path "$PSScriptRoot/..").Path
)

$ErrorActionPreference = "Stop"

# Only name/RGB facts are read from Kitty's protocol data; upstream code is never executed.
# Protocol reference: https://sw.kovidgoyal.net/kitty/color-stack/#color-value-encoding
$revision = "1c5a4829ae4dd472017f592b1424381d5ece7575"
$expectedHash = "255914422A50DB71C07B7DE905C919FF44DB90F7EE0FAFFD0D2FD60D26B794FE"
$url = "https://raw.githubusercontent.com/kovidgoyal/kitty/$revision/gen/color_names.py"
$dataDir = Join-Path $Root "build/kitty-color-data/$revision"
New-Item -ItemType Directory -Force -Path $dataDir | Out-Null
$sourcePath = Join-Path $dataDir "color_names.py"
if (-not (Test-Path $sourcePath)) {
    Invoke-WebRequest -Uri $url -OutFile $sourcePath
}
if ((Get-FileHash $sourcePath -Algorithm SHA256).Hash -ne $expectedHash) {
    throw "Kitty color-name source does not match the pinned SHA256."
}

$source = Get-Content $sourcePath -Raw
$data = [regex]::Match($source, '(?s)# BEGIN_DATA_SECTION.*?# END_DATA_SECTION').Value
$rows = [regex]::Matches($data, "(?m)^    '([a-z0-9 ]+)': Color\((\d+), (\d+), (\d+)\),\r?$")
if ($rows.Count -ne 753) {
    throw "Expected 753 named colors, found $($rows.Count)."
}
$colors = [System.Collections.Generic.SortedDictionary[string, int]]::new([StringComparer]::Ordinal)
foreach ($row in $rows) {
    $name = $row.Groups[1].Value
    $red = [int] $row.Groups[2].Value
    $green = [int] $row.Groups[3].Value
    $blue = [int] $row.Groups[4].Value
    if ($red -gt 255 -or $green -gt 255 -or $blue -gt 255) {
        throw "Invalid channel in $name."
    }
    $colors.Add($name, ($red -shl 16) -bor ($green -shl 8) -bor $blue)
}

