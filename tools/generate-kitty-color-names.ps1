package io.github.ketraterm.parser.ansi.osc

// Generated by tools/generate-kitty-color-names.ps1; do not edit manually.
// Protocol name/RGB facts: $url
internal object GeneratedKittyColorNames {
    private val names =
        arrayOf(
"@
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add($header)
foreach ($name in $colors.Keys) {
    $lines.Add("            `"$name`",")
}
$lines.Add("        )")
$lines.Add("")
$lines.Add("    private val colors =")
$lines.Add("        intArrayOf(")
foreach ($color in $colors.Values) {
    $lines.Add(("            0x{0:x6}," -f $color))
}
$lines.Add("        )")
$lines.Add(@'

    fun lookup(
        payload: ByteArray,
        start: Int,
        end: Int,
    ): Int {
        var low = 0
        var high = names.lastIndex
        while (low <= high) {
            val middle = (low + high) ushr 1
            val name = names[middle]
            val length = end - start
            val comparedLength = minOf(length, name.length)
            var index = 0
            var difference = 0
            while (index < comparedLength) {
                var byte = payload[start + index].toInt() and 0xff
                if (byte in 'A'.code..'Z'.code) byte += 'a'.code - 'A'.code
                difference = byte - name[index].code
                if (difference != 0) break
                index++
            }
            if (difference == 0) difference = length - name.length
            when {
                difference < 0 -> high = middle - 1
                difference > 0 -> low = middle + 1
                else -> return colors[middle]
            }
        }
        return -1
    }
}
'@)
$destination = Join-Path $Root "ketraterm-parser/src/main/kotlin/io/github/ketraterm/parser/ansi/osc/GeneratedKittyColorNames.kt"
$output = (($lines -join "`n").Replace("`r`n", "`n") + "`n").Replace("`n", [Environment]::NewLine)
[System.IO.File]::WriteAllText($destination, $output, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated $($colors.Count) Kitty named colors."
