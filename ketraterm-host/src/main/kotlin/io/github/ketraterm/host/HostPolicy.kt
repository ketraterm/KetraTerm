package io.github.ketraterm.host

/**
 * Host-facing security policy for terminal controls that can affect host state,
 * retain host metadata, or write terminal-generated bytes back to the remote
 * process.
 *
 * The parser only recognizes protocols. This policy is evaluated in the host
 * adapter before commands touch core state, host callbacks, metadata registries,
 * or terminal-to-host response queues.
 * Encoding validity is fixed by the OSC protocol contract before permission
 * evaluation; permitting a command does not permit malformed structured data.
 *
 * @property titlePolicy session-wide policy for OSC title updates and
 * title-stack restore operations before adapter/core title metadata changes or
 * host callbacks are emitted.
 * @property progressPolicy independent permission for OSC 9;4 reports. Denial suppresses
 * accepted progress callbacks; session policy replacement also clears retained progress.
 * Title, notification and window permissions do not govern progress.
 * @property hyperlinkPolicy whether OSC 8 hyperlinks may be retained and
 * attached to written cells.
 * @property currentWorkingDirectoryPolicy whether OSC 7 current-working-directory
 * reports may be retained and forwarded to the host.
 * @property notificationPolicy whether terminal-triggered desktop notification
 * requests may be forwarded to the host.
 * @property windowManipulationPolicy whether terminal-triggered window movement,
 * resize, minimize, raise, lower, and maximize requests may be forwarded.
 * Logical DECCOLM column switches are independent of this policy.
 * @property palettePolicy whether OSC palette updates, color-stack operations,
 * and palette queries may affect core color state or enqueue terminal-to-host bytes.
 * @property terminalResponsePolicy whether DA, DSR/CPR (including light/dark
 * scheme queries), DECRQM mode reports, window reports, DECRQCRA,
 * DECRQSS, XTGETTCAP, OSC 21 colors, Kitty graphics, and OSC 52 reads may enqueue terminal-to-host response bytes.
 * DENY also suppresses unsupported-mode, DECRQSS, and graphics failure replies.
 * OSC 52 reads also require clipboard read permission; denying responses suppresses
 * their empty failure replies too. Clipboard writes are unaffected.
 * OSC 21 also requires palette permission; response denial suppresses unknown-key replies
 * while permitted color mutations still apply.
 * @property clipboardPolicy deny-by-default permission and audit policy for
 * terminal-triggered clipboard protocols such as OSC 52.
 * @property maxHyperlinkEntries maximum distinct OSC 8 hyperlink keys retained
 * after an accepted open. Lowering the limit defers least-recently-used eviction
 * until the next accepted open, including explicit-key reuse; policy replacement
 * itself does not mutate the registry or notify listeners.
 * @property maxHyperlinkUriLength maximum accepted OSC 8 URI length in UTF-16
 * code units. Longer URIs are ignored and mapped to no active hyperlink.
 * @property maxHyperlinkIdLength maximum accepted OSC 8 `id=` parameter length
 * in UTF-16 code units. Longer IDs are ignored and mapped to no active
 * hyperlink.
 * @property maxNotificationTitleLength maximum retained UTF-16 code units for
 * desktop notification titles, without splitting a valid surrogate pair.
 * @property maxNotificationBodyLength maximum retained UTF-16 code units for
 * desktop notification bodies, without splitting a valid surrogate pair.
 * @property maxCurrentWorkingDirectoryUriLength maximum accepted OSC 7 file URI
 * length in UTF-16 code units. Longer or malformed URIs are ignored.
 */
public data class HostPolicy(
    val titlePolicy: TerminalTitlePolicy = TerminalTitlePolicy(),
    val hyperlinkPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val currentWorkingDirectoryPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val notificationPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val windowManipulationPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val palettePolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val terminalResponsePolicy: HostControlPolicy = HostControlPolicy.ALLOW,
    val clipboardPolicy: TerminalClipboardPolicy = TerminalClipboardPolicy(),
    val maxHyperlinkEntries: Int = 4096,
    val maxHyperlinkUriLength: Int = 4096,
    val maxHyperlinkIdLength: Int = 256,
    val maxNotificationTitleLength: Int = 256,
    val maxNotificationBodyLength: Int = 1024,
    val maxCurrentWorkingDirectoryUriLength: Int = 4096,
    val progressPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
) {
    // These internal declarations retain the original JVM constructor/copy and
    // compiler-generated default-argument signatures. Their JVM visibility also
    // preserves existing Java source; Kotlin callers use the new primary API.
    @PublishedApi
    internal constructor(
        titlePolicy: TerminalTitlePolicy = TerminalTitlePolicy(),
        hyperlinkPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        currentWorkingDirectoryPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        notificationPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        windowManipulationPolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        palettePolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        terminalResponsePolicy: HostControlPolicy = HostControlPolicy.ALLOW,
        clipboardPolicy: TerminalClipboardPolicy = TerminalClipboardPolicy(),
        maxHyperlinkEntries: Int = 4096,
        maxHyperlinkUriLength: Int = 4096,
        maxHyperlinkIdLength: Int = 256,
        maxNotificationTitleLength: Int = 256,
        maxNotificationBodyLength: Int = 1024,
        maxCurrentWorkingDirectoryUriLength: Int = 4096,
    ) : this(
        titlePolicy = titlePolicy,
        hyperlinkPolicy = hyperlinkPolicy,
        currentWorkingDirectoryPolicy = currentWorkingDirectoryPolicy,
        notificationPolicy = notificationPolicy,
        windowManipulationPolicy = windowManipulationPolicy,
        palettePolicy = palettePolicy,
        terminalResponsePolicy = terminalResponsePolicy,
        clipboardPolicy = clipboardPolicy,
        maxHyperlinkEntries = maxHyperlinkEntries,
        maxHyperlinkUriLength = maxHyperlinkUriLength,
        maxHyperlinkIdLength = maxHyperlinkIdLength,
        maxNotificationTitleLength = maxNotificationTitleLength,
        maxNotificationBodyLength = maxNotificationBodyLength,
        maxCurrentWorkingDirectoryUriLength = maxCurrentWorkingDirectoryUriLength,
        progressPolicy = HostControlPolicy.ALLOW,
    )

    @PublishedApi
    @JvmName("copy")
    internal fun copyCompatibility(
        titlePolicy: TerminalTitlePolicy = this.titlePolicy,
        hyperlinkPolicy: HostControlPolicy = this.hyperlinkPolicy,
        currentWorkingDirectoryPolicy: HostControlPolicy = this.currentWorkingDirectoryPolicy,
        notificationPolicy: HostControlPolicy = this.notificationPolicy,
        windowManipulationPolicy: HostControlPolicy = this.windowManipulationPolicy,
        palettePolicy: HostControlPolicy = this.palettePolicy,
        terminalResponsePolicy: HostControlPolicy = this.terminalResponsePolicy,
        clipboardPolicy: TerminalClipboardPolicy = this.clipboardPolicy,
        maxHyperlinkEntries: Int = this.maxHyperlinkEntries,
        maxHyperlinkUriLength: Int = this.maxHyperlinkUriLength,
        maxHyperlinkIdLength: Int = this.maxHyperlinkIdLength,
        maxNotificationTitleLength: Int = this.maxNotificationTitleLength,
        maxNotificationBodyLength: Int = this.maxNotificationBodyLength,
        maxCurrentWorkingDirectoryUriLength: Int = this.maxCurrentWorkingDirectoryUriLength,
    ): HostPolicy =
        copy(
            titlePolicy = titlePolicy,
            hyperlinkPolicy = hyperlinkPolicy,
            currentWorkingDirectoryPolicy = currentWorkingDirectoryPolicy,
            notificationPolicy = notificationPolicy,
            windowManipulationPolicy = windowManipulationPolicy,
            palettePolicy = palettePolicy,
            terminalResponsePolicy = terminalResponsePolicy,
            clipboardPolicy = clipboardPolicy,
            maxHyperlinkEntries = maxHyperlinkEntries,
            maxHyperlinkUriLength = maxHyperlinkUriLength,
            maxHyperlinkIdLength = maxHyperlinkIdLength,
            maxNotificationTitleLength = maxNotificationTitleLength,
            maxNotificationBodyLength = maxNotificationBodyLength,
            maxCurrentWorkingDirectoryUriLength = maxCurrentWorkingDirectoryUriLength,
            progressPolicy = progressPolicy,
        )

    init {
        require(maxHyperlinkEntries > 0) {
            "maxHyperlinkEntries must be positive, got $maxHyperlinkEntries"
        }
        require(maxHyperlinkUriLength >= 0) {
            "maxHyperlinkUriLength must be non-negative, got $maxHyperlinkUriLength"
        }
        require(maxHyperlinkIdLength >= 0) {
            "maxHyperlinkIdLength must be non-negative, got $maxHyperlinkIdLength"
        }
        require(maxNotificationTitleLength >= 0) {
            "maxNotificationTitleLength must be non-negative, got $maxNotificationTitleLength"
        }
        require(maxNotificationBodyLength >= 0) {
            "maxNotificationBodyLength must be non-negative, got $maxNotificationBodyLength"
        }
        require(maxCurrentWorkingDirectoryUriLength >= 0) {
            "maxCurrentWorkingDirectoryUriLength must be non-negative, got $maxCurrentWorkingDirectoryUriLength"
        }
    }
}

/**
 * Binary decision for host-affecting terminal controls.
 *
 * Policy decisions are intentionally explicit instead of inferred from size
 * limits. A denied family is ignored before it mutates metadata or emits host
 * callbacks, even when payload lengths are otherwise valid.
 */
public enum class HostControlPolicy {
    /**
     * Ignore the terminal control family at the host adapter boundary.
     */
    DENY,

    /**
     * Accept the terminal control family subject to protocol-specific bounds.
     */
    ALLOW,
}
